"""Build all pages from one shell; output works on Pages and in the desktop app."""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    'index.html': ('INDEX', '인게임 검색', '상점·창고 옵션을 골라 검색식을 복사하세요.'),
    'trade.html': ('TRADE', '거래 검색', '아이템 조건을 만들고, 공식 거래소에서 확인하세요.'),
    'filter.html': ('FILTER', '아이템 필터', '필터 표시를 수정하고, 검사 후 저장하세요.'),
    'currency-aliases.html': ('DICTIONARY', '재화 사전', '재화 이름과 약칭을 찾아 필터에 활용하세요.'),
}

def render_pages():
    shell = (ROOT / 'ui/shell.html').read_text(encoding='utf-8')
    digest = hashlib.sha256(b''.join(path.read_bytes() for path in sorted((ROOT / 'docs').glob('*.css')))).hexdigest()[:12]
    result = {}
    for filename, (active, title, description) in PAGES.items():
        source = (ROOT / 'ui/pages' / filename).read_text(encoding='utf-8')
        match = re.search(r'(<body\b[^>]*>)(.*)(</body>)', source, re.S)
        if not match:
            raise ValueError(f'Missing body: {filename}')
        common = shell.replace('{{TITLE}}', title).replace('{{DESCRIPTION}}', description)
        for key, _, _ in PAGES.values():
            common = common.replace('{{NAV_' + key + '}}', 'aria-current="page"' if key == active else '')
        common = common.replace('{{MASCOT}}', {'INDEX':'welcome','TRADE':'inspect','FILTER':'rune','DICTIONARY':'sleep'}[active])
        common = common.replace('{{CONTENT}}', match[2])
        output = source[:match.start()] + match[1] + common + match[3] + source[match.end():]
        output = re.sub(r'(href="(?:style|trade|filter|currency-aliases)\.css)\?[^"]+', lambda m: m[1] + '?v=' + digest, output)
        output = output.replace('{{SHARED_STYLES}}', f'<link rel="stylesheet" href="site-shell.css?v={digest}"><link rel="stylesheet" href="workshop-theme.css?v={digest}">')
        if '{{' in output:
            raise ValueError(f'Unresolved template marker: {filename}')
        result[filename] = '<!-- Generated by scripts/build_web.py; edit ui/pages/ and ui/shell.html. -->\n' + output
    return result

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Fail if generated pages are stale')
    args = parser.parse_args()
    stale = []
    for name, content in render_pages().items():
        target = ROOT / 'docs' / name
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != content:
                stale.append(name)
        else:
            target.write_text(content, encoding='utf-8')
    if stale:
        raise SystemExit('Run python scripts/build_web.py: ' + ', '.join(stale))
    print('Shared shell: 4 pages ' + ('verified' if args.check else 'built'))

if __name__ == '__main__':
    main()
